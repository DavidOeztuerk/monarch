#!/usr/bin/env python3
"""One-time generator for src/Monarch.Policy/CaseFoldTable.cs (ADR-0011 rule 8, Q-0122).

Usage: python3 -I tools/gen-casefold.py CaseFolding.txt > src/Monarch.Policy/CaseFoldTable.cs
Input: Unicode CaseFolding.txt (https://www.unicode.org/Public/UCD/latest/ucd/CaseFolding.txt). No runtime download.
Keeps status C and F entries with a non-ASCII source whose result is pure ASCII (1->n included).
"""
import sys

version = None
entries = []
with open(sys.argv[1], encoding="utf-8") as f:
    for line in f:
        if version is None and line.startswith("# CaseFolding-"):
            version = line.strip("# \n")
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        code, status, mapping = [p.strip() for p in body.split(";")[:3]]
        if status not in ("C", "F"):
            continue
        src = int(code, 16)
        result = "".join(chr(int(h, 16)) for h in mapping.split())
        if src < 0x80 or not all(ord(c) < 0x80 for c in result):
            continue
        entries.append((src, status, result))

print("// <auto-generated>")
print("// Generated by tools/gen-casefold.py from Unicode CaseFolding.txt (%s)." % version)
print("// Source: https://www.unicode.org/Public/UCD/latest/ucd/CaseFolding.txt, status C and F, non-ASCII source, pure-ASCII result.")
print("// Do not edit; regenerate with the script. ASCII upper case is folded in code, not listed here.")
print("// </auto-generated>")
print("#nullable enable")
print("namespace Monarch.Policy;")
print()
print("internal static class CaseFoldTable")
print("{")
print("    /// <summary>Unicode version of the source file.</summary>")
print('    public const string UnicodeVersion = "%s";' % version)
print()
print("    /// <summary>Folds one non-ASCII code point; null if it is not in the table.</summary>")
print("    public static string? Lookup(int codePoint) => codePoint switch")
print("    {")
for src, status, result in entries:
    print('        0x%04X => "%s", // %s' % (src, result, status))
print("        _ => null,")
print("    };")
print("}")
